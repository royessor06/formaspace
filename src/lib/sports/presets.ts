export function createInitialScene(sport: SportPresetId = 'custom'): {
  version: 1;
  units: 'metric';
  gridSize: number;
  elements: SceneElement[];
} {
  const preset = SPORT_PRESETS[sport] ?? SPORT_PRESETS.custom;
  return {
    version: 1,
    units: 'metric',
    gridSize: 1,
    elements: preset.buildElements(),
  };
}

